#!/usr/bin/env node
// The site editor: /crm/site-editor/ (dist/site-editor). The designer opens it, sees the real Hebrew pages in a frame,
// clicks a text and types, adds content, leaves notes, and sends everything to Hanoch by email (before / after).
//
//   node site/editor/build.mjs            (after `node site/build.mjs`, or on its own: it builds what it needs)
//
// It writes:
//   dist/site-editor/frame/     the site's pages for the frame: site/build.mjs with SITE_EDITOR_FRAME=1 (same pages,
//                               noindex, a CSP without require-trusted-types so the editor can put edited text back in
//                               place). The public site (dist/site) and its CSP are untouched.
//   dist/site-editor/index.html the editor (site/editor/index.html + the brand mark)
//   dist/site-editor/editor.js, frame-editor.css
//   dist/site-editor/data.js    window.TEXTS: every Hebrew text of the site (site/tools/editor-data.mjs)
//
// The email address the editor sends to is never in the repository: it comes from the link, #to=<address>.
// Work stays in the browser (localStorage) until it is sent. ROUND starts a new, empty list of changes for the
// person editing (their earlier work is kept in that browser): change it only when a round of fixes went live.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, rmSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { editorTexts } from '../tools/editor-data.mjs';
import { logo } from '../lib/brand.mjs';

export const ROUND = '2026-11-24';

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = resolve(HERE, '..');
const ROOT = resolve(SITE, '..');
const env = process.env;
const BASE = (env.SITE_EDITOR_BASE || '/crm/site-editor/').replace(/\/?$/, '/');
const OUT = resolve(ROOT, env.SITE_EDITOR_OUT || 'dist/site-editor');
const FRAME = join(OUT, 'frame');

const fail = (m) => {
  console.error(`\n✗ site editor build failed: ${m}\n`);
  process.exit(1);
};
if (!OUT.startsWith(resolve(ROOT, 'dist') + '/') && !env.SITE_EDITOR_OUT) fail(`unexpected output folder ${OUT}`);

// 1. the frame: the site's own build, into the editor's folder
for (const f of ['index.html', 'editor.js', 'frame-editor.css', 'data.js']) rmSync(join(OUT, f), { force: true });
mkdirSync(OUT, { recursive: true });
const r = spawnSync(process.execPath, [join(SITE, 'build.mjs'), '--quiet'], {
  env: { ...env, SITE_PREVIEW: '', SITE_EDITOR_FRAME: '1', SITE_ROBOTS: 'noindex', SITE_BASE: BASE + 'frame/', SITE_OUT: FRAME },
  stdio: 'inherit',
});
if (r.status !== 0) fail('the frame build (site/build.mjs) failed');
if (!existsSync(join(FRAME, 'index.html'))) fail('the frame build wrote no home page');

// 2. the texts
const texts = await editorTexts({ siteDir: SITE, frameDir: FRAME, round: ROUND });
const ver = createHash('sha256')
  .update(JSON.stringify(texts) + readFileSync(join(HERE, 'editor.js')) + readFileSync(join(HERE, 'frame-editor.css')) + readFileSync(join(HERE, 'index.html')))
  .digest('hex')
  .slice(0, 8);
texts.v = ver;
const json = JSON.stringify(texts).replace(/</g, '\\u003c').replace(/[\u2028\u2029]/g, (c) => (c === '\u2028' ? '\\u2028' : '\\u2029'));
writeFileSync(join(OUT, 'data.js'), `// Generated by site/editor/build.mjs from site/content — do not edit.\nwindow.TEXTS = ${json};\n`);

// 3. the editor
const page = readFileSync(join(HERE, 'index.html'), 'utf8')
  .replaceAll('{{LOGO}}', logo({ variant: 'lockup', label: 'המשך תנועה', className: 'logo' }).toString())
  .replaceAll('{{V}}', ver);
if (/\{\{[A-Z]+\}\}/.test(page)) fail('site/editor/index.html has a placeholder the build does not fill');
writeFileSync(join(OUT, 'index.html'), page);
copyFileSync(join(HERE, 'editor.js'), join(OUT, 'editor.js'));
copyFileSync(join(HERE, 'frame-editor.css'), join(OUT, 'frame-editor.css'));
writeFileSync(join(OUT, 'robots.txt'), `User-agent: *\nDisallow: ${BASE}\n`);

if (!process.argv.includes('--quiet'))
  console.log(`✓ site editor built → ${OUT.replace(ROOT + '/', '')} (${texts.items.length} texts, ${texts.groups.length - 1} pages) · ${BASE}`);
